def get_curated_city_by_id(city_id: str) -> Optional[Dict[str, Any]]:
    """Retrieve curated city profile by normalized lowercase id."""
    target_id = city_id.strip().lower()
    for city in CURATED_CITIES_DATA:
        if city["id"].lower() == target_id:
            return deepcopy(city)
    return None


def get_curated_benchmark_pool(exclude_city_id: Optional[str] = None) -> List[Dict[str, Any]]:
    """Retrieve benchmark candidate pool, optionally excluding target city."""
    exc_id = exclude_city_id.strip().lower() if exclude_city_id else None
    return [
        deepcopy(city)
        for city in CURATED_CITIES_DATA
        if not exc_id or city["id"].lower() != exc_id
    ]

